"""Assemble generated artifacts in a staging directory; installation is owned by ServiceManagement."""

from __future__ import annotations

import json
import os
import platform
import shutil
import subprocess
import tempfile
from pathlib import Path

from .layout import prepare_metadata
from .signing import sign_authorization


def assemble(core: Path, layout: dict, metadata: Path, binaries: Path, output: Path, finalize=None) -> None:
    if output.name != layout["authorizationApp"]:
        raise ValueError("The authorization app name must match the runtime descriptor")
    output.parent.mkdir(parents=True, exist_ok=True)
    if output.exists():
        marker = output / "Contents/Resources/native-package.json"
        if output.is_symlink() or not marker.is_file() or json.loads(marker.read_text()).get("generator") != "spaceprune-native-package":
            raise ValueError("Refusing to replace a directory not generated by this packager")
    with tempfile.TemporaryDirectory(prefix="spaceprune-native-stage-", dir=output.parent) as stage:
        app = Path(stage) / output.name
        contents = app / "Contents"
        (contents / "MacOS").mkdir(parents=True)
        (contents / "Resources").mkdir()
        (contents / "Library/LaunchServices").mkdir(parents=True)
        (contents / "Library/LaunchDaemons").mkdir()
        shutil.copy2(metadata / "authorization-info.plist", contents / "Info.plist")
        shutil.copy2(metadata / "native-package.json", contents / "Resources/native-package.json")
        shutil.copy2(core / "LICENSE", contents / "Resources/CORE-LICENSE.txt")
        shutil.copy2(binaries / layout["authorizationExecutable"], contents / "MacOS" / layout["authorizationExecutable"])
        for service in layout["services"]:
            shutil.copy2(binaries / service["binary"], app / service["bundleProgram"])
            shutil.copy2(metadata / service["plist"], contents / "Library/LaunchDaemons" / service["plist"])
        if finalize:
            finalize(app)
        # Only a previously generated build artifact is replaced, never an installed OS job.
        if output.exists():
            old = Path(stage) / "previous.app"
            output.rename(old)
            try:
                app.rename(output)
            except BaseException:
                old.rename(output)
                raise
        else:
            app.rename(output)


def build(core: Path, layout: dict, target: str, profile: str, version: str, output: Path, identity: str | None) -> dict:
    if platform.system() != "Darwin":
        raise ValueError("Building and signing native components requires macOS and its SDK")
    if identity:
        subprocess.run(["git", "diff", "--exit-code", "HEAD", "--", "."], cwd=core, check=True, stdout=subprocess.DEVNULL)
    cargo = json.loads(subprocess.check_output(["cargo", "metadata", "--locked", "--format-version", "1", "--no-deps"], cwd=core, text=True))
    target_directory = Path(cargo["target_directory"])
    revision = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=core, text=True).strip()
    metadata = target_directory / "macos-native-metadata" / layout["distribution"] / target / profile
    additions = prepare_metadata(layout, target, version, metadata, revision)
    environment = {**os.environ, **additions, "SPACEPRUNE_MACOS_DISTRIBUTION": layout["distribution"]}
    environment["MACOSX_DEPLOYMENT_TARGET"] = "10.13" if target.startswith("x86_64") else "11.0"
    subprocess.run(["cargo", "build", "--locked", "--package", "spaceprune-readonly-helper", "--target", target,
                    *(["--release"] if profile == "release" else [])], cwd=core, env=environment, check=True)
    binaries = target_directory / target / profile
    native = platform.machine() == ("x86_64" if target.startswith("x86_64") else "arm64")
    if native:
        for service in layout["services"]:
            subprocess.run([str(binaries / service["binary"]), service["probe"]], check=True)
        subprocess.run([str(binaries / layout["authorizationExecutable"]), layout["authorizationProbe"]], check=True)
    finalize = (lambda app: sign_authorization(app, layout, identity)) if identity else None
    assemble(core, layout, metadata, binaries, output, finalize)
    return {"app": str(output), "metadata": str(metadata), "nativeProbesExecuted": native, "signed": bool(identity)}
